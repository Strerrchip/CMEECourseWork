# Assigning variables
a = 5
b = 2.5
c = "Hello"
d = True

# Display variable values
print("Integer a:", a)
print("Float b:", b)
print("String c:", c)
print("Boolean d:", d)

# Arithmetic operations
sum_ab = a + b
product_ab = a * b

print("Sum of a and b:", sum_ab)
print("Product of a and b:", product_ab)

# Type conversion
a_str = str(a)
b_int = int(b)
print("Converted a to string:", a_str)
print("Converted b to integer:", b_int)

# String concatenation
greeting = c + " world!"
print(greeting)
